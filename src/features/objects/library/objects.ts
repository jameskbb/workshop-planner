export const BUILTIN_OBJECTS: readonly ObjectDefinition[] = [...workSurfaces, ...tools, ...storage, ...misc];

export const BUILTIN_OBJECTS_BY_ID: ReadonlyMap<string, ObjectDefinition> = new Map(BUILTIN_OBJECTS.map((d) => [d.id, d]));

export function builtinObject(id: string): ObjectDefinition {
  const d = BUILTIN_OBJECTS_BY_ID.get(id.startsWith('builtin:') ? id : `builtin:${id}`);
  if (!d) throw new Error(`Unknown built-in object "${id}"`);
  return d;
}

export const LIBRARY_GROUPS: ReadonlyArray<{ id: string; title: string; filter: (d: ObjectDefinition) => boolean }> = [
  { id: 'work-surfaces', title: 'Work surfaces', filter: (d) => d.category === 'work-surface' },
  { id: 'tools', title: 'Stationary tools', filter: (d) => d.category === 'stationary-tool' || (d.category === 'dust-collection' && d.id === 'builtin:dust-collector') },
  { id: 'storage', title: 'Storage', filter: (d) => d.category === 'storage' },
  { id: 'misc', title: 'Miscellaneous', filter: (d) => d.category === 'misc' || (d.category === 'dust-collection' && d.id !== 'builtin:dust-collector') },
];

/** Case-insensitive search over names, tags and categories. */
export function searchLibrary(defs: readonly ObjectDefinition[], query: string): ObjectDefinition[] {
  const q = query.trim().toLowerCase();
  if (!q) return [...defs];
  const words = q.split(/\s+/);
  return defs.filter((d) => {
    const hay = [d.name, d.category, d.subcategory ?? '', ...d.tags].join(' ').toLowerCase();
    return words.every((w) => hay.includes(w));
  });
}
